/** Translate a content string (vocabulary/meaning/instruction) to the current UI language. */
export function translateContent(english: string, language: AppLanguage): string {
  if (!english) return english;
  const map = contentTranslations[language];
  if (!map) return english;
  // Try exact, then trimmed match
  return map[english] ?? map[english.trim()] ?? english;
}
